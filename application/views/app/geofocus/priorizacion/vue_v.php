                .sort((a, b) => b.properties.__priority_value - a.properties.__priority_value
                    || this.normalizeMapJoinKey(a.properties[propertyKey]).localeCompare(
                        this.normalizeMapJoinKey(b.properties[propertyKey]), 'es', { numeric: true })
                    || a.id - b.id)
                .slice(0, polygonLimit)
                .reverse()
