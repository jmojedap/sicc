                && !this.descripcion.loading && !this.priorizacionPendienteDeCalculo && this.descripcion.texto.trim() !== ''
        },
        // 2026-10-12: habilitar un único aviso cuando mapa y descripción del mismo cálculo estén listos y visibles.
        canNotifyCalculationCompletion: function(){
            const completion = this.calculationCompletion
            return completion.runId === calculationRunId && completion.mapReady && completion.descriptionReady
                && !completion.notified && this.descriptionVisible && !this.mapLoading && !this.mapError
        },
        // Obtiene las filas visibles para informar cuando los filtros no tienen coincidencias.
        // 2026-10-12
        variablesFiltradas: function(){
            return this.variables.filter(variable => this.matchesVariableFilters(variable))
        },
        // Lista los temas presentes en las variables disponibles de esta priorización.
        // 2026-10-12
        variablesTemas: function(){
            return [...new Set(this.variables
                .filter(variable => Number(variable.estado) === 1)
                .map(variable => (variable.tema || '').trim())
                .filter(tema => tema.length > 0))]
                .sort((a, b) => a.localeCompare(b, 'es'))
        },
        // 2026-10-11: se retira aiVariablesProposal; la única tabla muestra los controles ya aplicados.
        descripcionHtml: function(){
            return this.markdownToHtml(this.descripcion.texto)
        },
        variablesActivas: function(){
            return this.variables.filter(variable => variable.active == true)
        },
        // Devuelve los temas que tienen variables activas en esta capa.
        mapTemas: function(){
            const availableThemes = new Set(
                this.variables
                    .filter(variable => String(variable.estado) === '1')
                    .map(variable => (variable.tema || '').trim())
                    .filter(theme => theme.length > 0)
            )
            return this.arrTemas
                .map(option => option.name)
                .filter(theme => availableThemes.has(theme))
        },
        // Filtra las variables disponibles en el selector del mapa.
        mapVariablesFiltradas: function(){
            return this.variables.filter(variable =>
                String(variable.estado) === '1' &&
                (!this.currentTema || (variable.tema || '').trim() === this.currentTema)
            )
        },
        textoParametrizacion: function(){
            var texto = 'Variables: '
            this.variables.forEach((variable,index) => {
                if ( variable.active ) {
                    texto += "Variable " + (index+1) + ': '
                    texto += `Nombre: ${variable.nombre}. `;
                    texto += `Tema: ${variable.tema}. `;
                    texto += `Descripción: ${variable.descripcion}. `;
                    if ( variable.tipo_priorizacion == 1 ) {
                        texto += `Tipo de priorización: Priorizar territorios con valores altos. `;
                    } else {
                        texto += `Tipo de priorización: Priorizar territorios con valores bajos. `;
                    }
                    texto += `Ponderación de la variable: ${variable.puntaje}. `;
                    texto += '. ---';
                    texto += "\n"
                }
            });
            return texto
        },
    },
    watch: {
        // 2026-10-12: esperar a que Vue pinte la descripción antes de notificar el éxito de ambos procesos.
        canNotifyCalculationCompletion: async function(ready){
            if ( !ready ) return
            await this.$nextTick()
            if ( !this.canNotifyCalculationCompletion ) return
            this.calculationCompletion.notified = true
            toastr['success']('El mapa y la descripción están listos.', 'Priorización completada')
        }
    },
    // Abre Variables con el formulario de IA integrado y restaura la configuración guardada del escenario.
    // 2026-10-11
    mounted(){
        this.startVariables()
        this.section = 'variables'
        const selectedVariable = this.variables.find(variable =>
            String(variable.estado) === '1'
        )
        if ( selectedVariable ) {
            this.currentVariableId = String(selectedVariable.id)
            this.currentVariable = selectedVariable
            this.currentTema = selectedVariable.tema || ''
        } else {
            this.currentVariableId = ''
            this.currentVariable = null
            this.currentTema = ''
        }
        this.mapMode = 'priorizacion'
        this.syncMapRotation()
    },
    // Cancela el revelado del resultado y descarta respuestas pendientes cuando se desmonta la vista.
    // 2026-10-12
    beforeUnmount(){
        calculationRunId += 1
        descriptionRequestId += 1
        priorizacionMapRequestId += 1
        this.calculationCompletion.mapReady = false
        this.calculationCompletion.descriptionReady = false
        this.stopResultReveal()
        if ( this.territoriosInterval !== null ) clearInterval(this.territoriosInterval)
    }
}).mount('#priorizacionApp');

